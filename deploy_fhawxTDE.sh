if [ -f "$SCRIPT_SRC_DIR/conf/fhawx_logo_ascii.txt" ]; then
    cp -f "$SCRIPT_SRC_DIR/conf/fhawx_logo_ascii.txt" "$TARGET_HOME/.config/fastfetch/fhawx_logo_ascii.txt"
