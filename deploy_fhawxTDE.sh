    echo "  Mode     : On-Demand CLI / SSH ('DOS Shell' Mode)"
    echo "  Launch   : Type 'fhawx' (or 'tde') in any terminal or SSH window!"
    echo "  Return   : Press 'Alt + Q' inside FhawxTDE to drop back to your normal shell."
