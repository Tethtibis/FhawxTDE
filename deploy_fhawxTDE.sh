# 4. APT Package Installation
echo "[+] Updating APT package indexes..."
apt-get update -y

CLI_PKGS=(
    tmux
    micro
    btop
    fzf
    curl
    git
    alsa-utils
    network-manager
    polkitd
    wireguard
    wireguard-tools
    ca-certificates
    python3
)

echo "[+] Installing core FhawxTDE terminal & network packages..."
apt-get install -y --no-install-recommends "${CLI_PKGS[@]}"

if [ "$KIOSK_MODE" -eq 1 ]; then
    echo "[+] Installing Micro-X11 Kiosk stack (--kiosk enabled)..."
    KIOSK_PKGS=(
        xserver-xorg
        xserver-xorg-legacy
        x11-xserver-utils
        xinit
        matchbox-window-manager
        xfce4-terminal
        chromium
        xdg-utils
        unclutter
        redshift
        fonts-dejavu-core
        fonts-terminus
    )
